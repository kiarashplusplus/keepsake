/**
 * Text measurement, wrapping and escaping for the share card — pure, no DOM,
 * no `Env`, no resvg. Split out from `card.ts` so the fiddly part can be unit
 * tested on its own and so the offline preview harness
 * (`tools/og/render-samples.mjs`) exercises exactly the code the Worker runs.
 *
 * The hard constraint: **resvg exposes no text-measuring API.** It rasterises
 * an SVG string; it will not tell you how wide a `<text>` came out. So every
 * line break on this card is decided here, in JavaScript, from a model of the
 * font's advance widths — and the model is necessarily approximate for a
 * proportional face.
 *
 * Three layers of defence, in order:
 *
 *   1. Courier Prime is **monospace**, so its advance is exactly
 *      `0.6 * fontSize` per character (the standard Courier advance, 600/1000
 *      units). Every eyebrow, place line, footer and stamp on the card is
 *      typeset in it, so those are exact, not estimated.
 *   2. Fraunces is proportional, and is modelled by a per-character advance
 *      table (`FRAUNCES_ADVANCE` below) **measured off the real font** by
 *      `tools/og/measure-advances.mjs`. What it still cannot see is kerning
 *      and shaping, so callers wrap to `WRAP_SAFETY` of the true column
 *      width to leave the residual error somewhere harmless.
 *   3. `card.ts` puts a `clipPath` at the paper object's inner edge. If the
 *      estimate is still too optimistic the text clips at the edge of the
 *      print — a slightly ugly card, never one with type bleeding onto the
 *      table.
 *
 * Do not "improve" this by measuring in a canvas: this module runs inside a
 * Cloudflare Worker, where there is no canvas and no font shaping engine.
 */
import { storyExcerpt } from "@keepsake/contracts/story";


/**
 * Per-character advance widths for Fraunces at `wght 600`, in ems.
 *
 * **Measured, not guessed.** Generated by rasterising each character nine
 * times through the same resvg build the card uses and taking
 * `(ink(9) - ink(1)) / 8`, which cancels the first and last glyph's side
 * bearings. The class-based estimate this replaced was 10-24% low — enough
 * that the title's clip-path backstop was visibly engaging on a long title
 * instead of sitting there unused as intended.
 *
 * Regenerate with `node tools/og/measure-advances.mjs` if the font file or
 * the title's weight ever changes. A character not in this table falls back
 * to {@link FRAUNCES_FALLBACK}, the median advance — safe for the accented
 * Latin the card admits, and irrelevant for anything else, which
 * `isRenderable` rejects outright.
 */
const FRAUNCES_CHARS = " !\"#$%&'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_`abcdefghijklmnopqrstuvwxyz{|}~Éáçèéñöü–—‘’“”…";
const FRAUNCES_ADVANCES = [
  0.2, 0.345, 0.449, 0.688, 0.631, 0.874, 0.804, 0.22, 0.401, 0.401, 0.625, 0.574,
  0.341, 0.403, 0.328, 0.512, 0.731, 0.511, 0.667, 0.619, 0.699, 0.634, 0.674, 0.573,
  0.693, 0.674, 0.328, 0.341, 0.531, 0.574, 0.531, 0.608, 0.993, 0.787, 0.774, 0.721,
  0.836, 0.691, 0.651, 0.785, 0.902, 0.463, 0.603, 0.865, 0.666, 0.988, 0.772, 0.804,
  0.767, 0.804, 0.831, 0.647, 0.746, 0.767, 0.759, 1.121, 0.754, 0.711, 0.662, 0.388,
  0.512, 0.398, 0.477, 0.524, 0.292, 0.603, 0.65, 0.557, 0.66, 0.56, 0.458, 0.619,
  0.686, 0.351, 0.352, 0.662, 0.351, 1.01, 0.686, 0.624, 0.665, 0.651, 0.535, 0.532,
  0.443, 0.675, 0.584, 0.89, 0.6, 0.608, 0.53, 0.429, 0.329, 0.429, 0.645, 0.691,
  0.603, 0.557, 0.56, 0.56, 0.686, 0.624, 0.675, 0.574, 0.895, 0.29, 0.29, 0.579,
  0.578, 1.048,
];
const FRAUNCES_FALLBACK = 0.62;

const FRAUNCES_ADVANCE = new Map<string, number>(
  [...FRAUNCES_CHARS].map((ch, i) => [ch, FRAUNCES_ADVANCES[i] as number]),
);

function frauncesAdvanceEm(ch: string): number {
  return FRAUNCES_ADVANCE.get(ch) ?? FRAUNCES_FALLBACK;
}

/** Courier Prime, like every Courier, advances 600/1000 units per glyph. */
const COURIER_ADVANCE_EM = 0.6;

export type CardFont = "fraunces" | "courier";

/**
 * Estimated width of `text` in user units. Exact for `"courier"`, modelled
 * for `"fraunces"` (see the file header). `letterSpacing` is in user units
 * and applies between glyphs, matching SVG's `letter-spacing` attribute.
 */
export function measureText(text: string, font: CardFont, fontSize: number, letterSpacing = 0): number {
  if (text.length === 0) return 0;
  let em = 0;
  for (const ch of text) {
    em += font === "courier" ? COURIER_ADVANCE_EM : frauncesAdvanceEm(ch);
  }
  return em * fontSize + letterSpacing * (text.length - 1);
}

/**
 * The margin left for what the advance table cannot model: kerning pairs and
 * any shaping resvg applies. With the measured table this is worth a couple
 * of percent, not the 15% the old class-based estimate needed — but it stays
 * at 4% because being slightly short of the column costs nothing and being
 * over engages the clip path. Courier lines are exact and do not need it;
 * they get it anyway, because one rule beats two.
 */
export const WRAP_SAFETY = 0.96;

export interface WrapOptions {
  font: CardFont;
  fontSize: number;
  /** Column width in user units, BEFORE the safety margin is applied. */
  maxWidth: number;
  /** Hard cap on lines. The last line is ellipsised if the text overruns. */
  maxLines: number;
  letterSpacing?: number;
}

/**
 * Greedy word wrap with an ellipsised final line.
 *
 * A single word longer than the column (a URL, a serial number, a German
 * compound) is broken mid-word rather than allowed to overhang — the clip
 * path would eat it otherwise, and a broken word reads better than a
 * truncated one.
 */
export function wrapText(input: string, opts: WrapOptions): string[] {
  const { font, fontSize, maxLines, letterSpacing = 0 } = opts;
  const limit = opts.maxWidth * WRAP_SAFETY;
  const words = input.split(/\s+/).filter((w) => w.length > 0);
  if (words.length === 0) return [];

  const lines: string[] = [];
  let current = "";

  const width = (s: string): number => measureText(s, font, fontSize, letterSpacing);

  for (let i = 0; i < words.length; i += 1) {
    let word = words[i] as string;

    // A word that cannot fit on a line of its own, ever. Break it at the
    // last character that fits and push the remainder back onto the queue.
    while (width(word) > limit) {
      let cut = 1;
      while (cut < word.length && width(`${word.slice(0, cut + 1)}-`) <= limit) cut += 1;
      if (cut >= word.length) break;
      const head = `${word.slice(0, cut)}-`;
      if (current.length > 0) {
        lines.push(current);
        current = "";
      }
      lines.push(head);
      word = word.slice(cut);
      if (lines.length >= maxLines) break;
    }

    const candidate = current.length === 0 ? word : `${current} ${word}`;
    if (width(candidate) <= limit) {
      current = candidate;
      continue;
    }
    if (current.length > 0) lines.push(current);
    current = word;

    if (lines.length >= maxLines) {
      // Everything from here on has to be folded into the ellipsis below.
      current = [current, ...words.slice(i + 1)].join(" ");
      break;
    }
  }

  if (current.length > 0) lines.push(current);
  if (lines.length <= maxLines) return lines;

  // Overflowed: keep `maxLines`, and make the last one end in an ellipsis at
  // a word boundary rather than mid-word.
  const kept = lines.slice(0, maxLines);
  let last = kept[maxLines - 1] as string;
  while (last.length > 0 && width(`${last}…`) > limit) {
    const space = last.lastIndexOf(" ");
    last = space === -1 ? last.slice(0, -1) : last.slice(0, space);
  }
  kept[maxLines - 1] = `${last.replace(/[\s,;:.—-]+$/, "")}…`;
  return kept;
}

/**
 * The card's story line: collapse the giver's line breaks first, then apply
 * the shared excerpt rule.
 *
 * The collapse is the card-specific half and is why this wrapper exists.
 * `storyExcerpt` treats `\n` as a sentence terminator, which is right for a
 * paragraph of prose and wrong here — a story typed with a hard wrap after
 * eight words would otherwise excerpt to those eight words. The card sets its
 * own line breaks (`wrapText`), so the source has to arrive as one run of
 * text.
 */
export function cardStoryExcerpt(story: string, maxChars = 160): string {
  return storyExcerpt(story.replace(/\s+/g, " ").trim(), maxChars);
}

/**
 * Whether both card fonts can actually draw this string.
 *
 * This matters more than it looks. resvg draws **nothing at all** for a glyph
 * no loaded font covers — not tofu, not a fallback box, just empty space
 * (linebender/resvg#159). A Cyrillic or CJK title would therefore render as a
 * silent hole in the card rather than as visibly-wrong text, and nobody would
 * ever notice it was broken. Fraunces and Courier Prime are Latin-only, so
 * `card.ts` checks this and drops the title line entirely rather than leaving
 * a gap where a title should be.
 *
 * The range is Latin-1 + Latin Extended-A/B (accented European text renders
 * fine) plus General Punctuation (curly quotes, em dashes, the ellipsis this
 * module itself inserts).
 */
const RENDERABLE = /^[ -ɏ‐-⁞\s]*$/;

export function isRenderable(text: string): boolean {
  return RENDERABLE.test(text);
}

/**
 * XML text-node and attribute-value escaping for SVG.
 *
 * Distinct from `escapeHtml` in `routes/item.ts`, which escapes for an HTML
 * attribute, and emphatically distinct from `lib/jsonLd.ts`, which must NOT
 * entity-escape at all. Three different destinations, three different rules —
 * the apostrophe is the tell: `&apos;` is valid XML but is not a predefined
 * HTML4 entity, so this function is not interchangeable with the other two.
 */
export function escapeXml(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}
